CREATE TABLE kpi_snapshot (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel       VARCHAR(16)  NOT NULL,
    report_day    DATE         NOT NULL,
    window_from   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    window_to     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    calculated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_kpi_snapshot_channel CHECK (channel IN ('local', 'report'))
);

CREATE TABLE kpi_snapshot_value (
    snapshot_id   BIGINT           NOT NULL,
    kpi_id        VARCHAR(64)      NOT NULL,
    sort_order    INTEGER          NOT NULL,
    numeric_value DOUBLE PRECISION,
    text_value    TEXT,
    CONSTRAINT pk_kpi_snapshot_value PRIMARY KEY (snapshot_id, kpi_id),
    CONSTRAINT fk_kpi_snapshot_value_snapshot FOREIGN KEY (snapshot_id) REFERENCES kpi_snapshot (id)
);
