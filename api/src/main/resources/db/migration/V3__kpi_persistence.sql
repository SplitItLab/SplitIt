CREATE TABLE request_sample (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    endpoint    VARCHAR(255) NOT NULL,
    status_code SMALLINT     NOT NULL,
    duration_us INTEGER      NOT NULL,
    recorded_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_request_sample_recorded_at ON request_sample (recorded_at);

CREATE TABLE kpi_run (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_day DATE         NOT NULL,
    ran_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    status     VARCHAR(16)  NOT NULL,
    CONSTRAINT ck_kpi_run_status CHECK (status IN ('sent', 'failed', 'skipped'))
);
